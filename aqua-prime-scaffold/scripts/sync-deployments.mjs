#!/usr/bin/env node
/**
 * Reads reference/swap-vm/deployments manifest and writes scaffold contract files.
 * PRIME_DESK_MANIFEST=fork|sepolia (default: fork for local Anvil)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const swapVmRoot = path.resolve(root, "../reference/swap-vm");

const profile = process.env.PRIME_DESK_MANIFEST ?? "fork";
const manifestName = profile === "sepolia" ? "aqua-prime-sepolia.json" : "aqua-prime-fork.json";
const manifestPath = path.resolve(swapVmRoot, "deployments", manifestName);
const contractsDir = path.resolve(root, "contracts");

if (!fs.existsSync(manifestPath)) {
  console.error(`Manifest not found: ${manifestPath}`);
  console.error(`Run DeployAquaPrime${profile === "sepolia" ? "Sepolia" : "Stack"} first.`);
  process.exit(1);
}

const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const gateway = manifest.gateway ?? manifest.forkTaker;
if (!gateway) {
  console.error("Manifest missing gateway address.");
  process.exit(1);
}

const chainId = manifest.chainId ?? 31337;
const weth = manifest.weth ?? manifest.baseToken ?? "0xC02aaA39b223FE8D0A0e5C4F27eAD9083C756Cc2";
const usdc = manifest.usdc ?? manifest.quoteToken ?? "0xA0b86991c6218b36c1d19D4a2e9Eb0cE3606eB48";
const aqua = manifest.aqua ?? "0x0000000000000000000000000000000000000000";
const router = manifest.swapVMRouter ?? "0x0000000000000000000000000000000000000000";
const primeSelector = manifest.primeSelector ?? "0x0000000000000000000000000000000000000000";
const maker = manifest.maker ?? manifest.deployer ?? "0x0000000000000000000000000000000000000000";
const rpcUrl = manifest.rpcUrl ?? (chainId === 11155111 ? "https://rpc.sepolia.org" : "http://127.0.0.1:8545");
const ensName = manifest.ensName ?? "maker.primedesk.eth";
const chainlinkEthUsd = manifest.chainlinkEthUsd ?? "0x694AA1769357215DE4FAC081bf1f309aDC325306";
const sampleQuote1Eth = manifest.sampleQuoteOut1Eth ?? manifest.sampleQuoteOut10kUsdc ?? null;
const subgraphUrl = process.env.NEXT_PUBLIC_SUBGRAPH_URL ?? "";
const mintable = manifest.mintableTokens === true;
const wethAbiName = mintable ? "faucetTokenAbi" : "wethAbi";
const usdcAbiName = mintable ? "faucetTokenAbi" : "erc20Abi";

const deployedContracts = `/**
 * Auto-generated by scripts/sync-deployments.mjs — do not edit by hand.
 * Source: reference/swap-vm/deployments/${manifestName}
 */
import { aquaPrimeGatewayAbi, erc20Abi, wethAbi, faucetTokenAbi } from "./abis";

export type ContractName = "AquaPrimeSwapGateway" | "WETH" | "USDC";

const deployedContracts = {
  ${chainId}: {
    AquaPrimeSwapGateway: {
      address: "${gateway}",
      abi: aquaPrimeGatewayAbi,
    },
    WETH: {
      address: "${weth}",
      abi: ${wethAbiName},
    },
    USDC: {
      address: "${usdc}",
      abi: ${usdcAbiName},
    },
  },
} as const;

export default deployedContracts;
`;

const manifestMeta = `/**
 * Auto-generated by scripts/sync-deployments.mjs — do not edit by hand.
 */
export const primeDeskManifest = {
  chainId: ${chainId},
  blockNumber: ${manifest.blockNumber ?? 0},
  rpcUrl: "${rpcUrl}",
  maker: "${maker}" as const,
  aqua: "${aqua}" as const,
  swapVMRouter: "${router}" as const,
  primeSelector: "${primeSelector}" as const,
  gateway: "${gateway}" as const,
  weth: "${weth}" as const,
  usdc: "${usdc}" as const,
  baseToken: "${weth}" as const,
  quoteToken: "${usdc}" as const,
  chainlinkEthUsd: "${chainlinkEthUsd}" as const,
  ensName: "${ensName}" as const,
  jarvisEns: "${manifest.jarvisEns ?? "jarvis.primedesk.eth"}" as const,
  subgraphUrl: "${subgraphUrl}",
  sampleQuoteOut1Eth: ${sampleQuote1Eth ?? "null"},
  mintable: ${mintable},
  deployed: ${gateway !== "0x0000000000000000000000000000000000000000"},
} as const;

/** @deprecated use primeDeskManifest */
export const aquaPrimeManifest = primeDeskManifest;
`;

fs.writeFileSync(path.join(contractsDir, "deployedContracts.ts"), deployedContracts);
fs.writeFileSync(path.join(contractsDir, "manifestMeta.ts"), manifestMeta);
console.log(`Synced ${manifestName} (gateway ${gateway}, chain ${chainId}) → contracts/`);
